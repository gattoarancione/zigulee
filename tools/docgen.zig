//! Writes the reference documentation: built-in elements (from the
//! compiler's tables) and standard widgets (from their `.zge` sources and
//! comments).
//!
//!     zig build docs                  rewrites docs/reference/*.md
//!     docgen <docs-dir> --check       fails if they are out of date, or if
//!                                     an example in the guides does not
//!                                     compile (a test)

const std = @import("std");
const Allocator = std.mem.Allocator;
const compiler = @import("zigulee-interpreter").compiler;
const ast = compiler.ast;
const types = compiler.types;
const std_widgets = compiler.std_widgets;

const header = "<!-- Generated by `zig build docs` (tools/docgen.zig). Do not edit. -->\n\n";

pub fn main(init: std.process.Init) !u8 {
    const arena = init.arena.allocator();
    const args = try init.minimal.args.toSlice(arena);
    if (args.len < 2) {
        std.debug.print("usage: docgen <docs-dir> [--check]\n", .{});
        return 2;
    }
    const check = args.len > 2 and std.mem.eql(u8, args[2], "--check");
    const docs = try std.Io.Dir.cwd().openDir(init.io, args[1], .{ .iterate = true });
    defer docs.close(init.io);
    const dir = try docs.createDirPathOpen(init.io, "reference", .{});
    defer dir.close(init.io);

    const pages = [_]struct { []const u8, []const u8 }{
        .{ "elements.md", try elements(arena) },
        .{ "widgets.md", try widgets(arena) },
    };
    var stale = false;
    for (pages) |page| {
        if (check) {
            const current = dir.readFileAlloc(init.io, page[0], arena, .unlimited) catch "";
            if (!std.mem.eql(u8, current, page[1])) {
                std.debug.print("docs/reference/{s} is out of date: run `zig build docs`\n", .{page[0]});
                stale = true;
            }
        } else try dir.writeFile(init.io, .{ .sub_path = page[0], .data = page[1] });
    }
    if (check) {
        var it = docs.iterate();
        while (try it.next(init.io)) |entry| {
            if (entry.kind != .file or !std.mem.endsWith(u8, entry.name, ".md")) continue;
            const text = try docs.readFileAlloc(init.io, entry.name, arena, .unlimited);
            if (!try examplesCompile(arena, entry.name, text)) stale = true;
        }
    }
    return if (stale) 1 else 0;
}

/// Compiles the complete examples (```slint blocks with an exported
/// component) of a guide.
fn examplesCompile(arena: Allocator, name: []const u8, text: []const u8) !bool {
    var ok = true;
    var rest = text;
    while (std.mem.indexOf(u8, rest, "```slint\n")) |start| {
        const body = rest[start + "```slint\n".len ..];
        const end = std.mem.indexOf(u8, body, "```") orelse break;
        const example = body[0..end];
        rest = body[end + 3 ..];
        if (std.mem.indexOf(u8, example, "export component") == null) continue;
        switch (try compiler.compile(arena, name, example, .{})) {
            .zig => {},
            .errors => |e| {
                std.debug.print("an example in docs/{s} does not compile:\n{s}\n", .{ name, e });
                ok = false;
            },
        }
    }
    return ok;
}

// ---- Built-in elements ----

fn elements(arena: Allocator) ![]const u8 {
    var out: std.Io.Writer.Allocating = .init(arena);
    const w = &out.writer;
    try w.writeAll(header);
    try w.writeAll(
        \\# Built-in elements
        \\
        \\The elements every `.zge` file can use. Components are made of them
        \\(and of other components). See the [language guide](../language.md).
        \\
        \\All elements have these properties:
        \\
        \\
    );
    try propTable(w, &types.geometry_props);
    try w.writeAll(
        \\
        \\In a layout, elements also take constraints, which the layout uses to
        \\size them (`min-width`, `preferred-height`, ...), and in a GridLayout
        \\their cell (`row`, `col`, `rowspan`, `colspan`):
        \\
        \\
    );
    try propTable(w, &types.constraint_props);
    try w.writeAll(
        \\| `row`, `col` | int | in |
        \\| `rowspan`, `colspan` | int | in |
        \\
    );
    try w.writeAll(
        \\
        \\All elements can also describe themselves to assistive technology
        \\(screen readers). The standard widgets set these; set them on your
        \\own components' elements:
        \\
        \\
    );
    try propTable(w, &types.accessible_props);
    try w.writeAll("\nand handle what assistive technology asks:\n\n");
    for (types.accessible_callbacks) |c| {
        try w.print("- `{s}(", .{c.name});
        for (c.params, 0..) |p, i| try w.print("{s}{s}", .{ if (i > 0) ", " else "", p.name() });
        try w.writeAll(")`\n");
    }
    for (types.builtins) |b| {
        try w.print("\n## {s}\n", .{b.name});
        if (b.doc.len > 0) try w.print("\n{s}\n", .{b.doc});
        if (!b.children) try w.writeAll("\nTakes no child elements.\n");
        if (b.props.len > 0) {
            try w.writeAll("\n");
            try propTable(w, b.props);
        }
        if (b.callbacks.len > 0) {
            try w.writeAll("\nCallbacks:\n\n");
            for (b.callbacks) |c| {
                try w.print("- `{s}(", .{c.name});
                for (c.params, 0..) |p, i| try w.print("{s}{s}", .{ if (i > 0) ", " else "", p.name() });
                try w.writeAll(")");
                if (c.ret != .void) try w.print(" -> {s}", .{c.ret.name()});
                try w.writeAll("`\n");
            }
        }
        if (b.functions.len > 0) {
            try w.writeAll("\nFunctions:");
            for (b.functions, 0..) |f, i| {
                try w.print("{s} `{s}(", .{ if (i > 0) "," else "", f.name });
                for (f.params, 0..) |t, j| try w.print("{s}{s}", .{ if (j > 0) ", " else "", t.name() });
                try w.writeAll(")");
                if (f.ret != .void) try w.print(" -> {s}", .{f.ret.name()});
                try w.writeAll("`");
            }
            try w.writeAll("\n");
        }
    }
    try w.writeAll(
        \\
        \\## Enumerations
        \\
        \\Values of enumeration properties, written without the type name
        \\(`wrap: word-wrap;`) or with it (`TextWrap.word-wrap`).
        \\
        \\| Type | Values |
        \\|---|---|
        \\
    );
    for (types.enums) |e| {
        try w.print("| `{s}` | ", .{e.name});
        for (e.values, 0..) |v, i| try w.print("{s}`{s}`", .{ if (i > 0) ", " else "", v[0] });
        try w.writeAll(" |\n");
    }
    return out.written();
}

fn propTable(w: *std.Io.Writer, props: []const types.Prop) !void {
    try w.writeAll("| Property | Type | Access |\n|---|---|---|\n");
    for (props) |p| try w.print("| `{s}` | {s} | {s} |\n", .{ p.name, p.ty.name(), if (p.read_only) "out (read-only)" else "in-out" });
}

// ---- Standard widgets ----

fn widgets(arena: Allocator) ![]const u8 {
    var out: std.Io.Writer.Allocating = .init(arena);
    const w = &out.writer;
    try w.writeAll(header);
    try w.writeAll(
        \\# Standard widgets
        \\
        \\Import them from `std-widgets.zge`:
        \\
        \\```
        \\import { Button, LineEdit, Palette } from "std-widgets.zge";
        \\```
        \\
        \\They are written in `.zge` ([src/widgets](../../src/widgets)) and come
        \\in three styles, chosen at build time: `fluent` (the default),
        \\`material` and `minimal`. The style changes their look (the `Palette`
        \\colors and `Style` sizes), not their properties. Besides the
        \\properties listed here, each has those of the element it inherits,
        \\and those of every element: `visible` and `enabled` among them
        \\(disabled, a widget greys itself and takes no input).
        \\
    );
    const index_path = std_widgets.root;
    const index_src = std_widgets.read(std_widgets.default_style, index_path).?;
    const index_doc = try parse(arena, index_src);
    // In the order of std-widgets.zge, globals last.
    var globals: std.ArrayList(Found) = .empty;
    for (index_doc.imports) |imp| for (imp.names) |name| {
        const path = try std.fmt.allocPrint(arena, "{s}/{s}", .{ std_widgets.dir, imp.path });
        const src = std_widgets.read(std_widgets.default_style, path) orelse return error.MissingWidgetFile;
        const doc = try parse(arena, src);
        for (doc.components) |*c| if (std.mem.eql(u8, c.name.name, name.name)) {
            const found: Found = .{ .comp = c, .src = src };
            if (c.is_global) try globals.append(arena, found) else try component(w, found);
        };
    };
    for (globals.items) |g| try component(w, g);
    return out.written();
}

const Found = struct { comp: *const ast.Component, src: []const u8 };

fn parse(arena: Allocator, src: []const u8) !ast.Document {
    var diags: compiler.Diagnostics = .{ .arena = arena };
    _ = try diags.addFile("widget.zge", src);
    var parser: compiler.Parser = .init(arena, src, &diags);
    return parser.parseDocument();
}

fn component(w: *std.Io.Writer, f: Found) !void {
    const c = f.comp;
    try w.print("\n## {s}\n\n", .{c.name.name});
    if (c.is_global) {
        try w.writeAll("A global: use its properties as `");
        try w.print("{s}.name`", .{c.name.name});
        if (std.mem.eql(u8, c.name.name, "Palette")) try w.writeAll(". The values depend on the style; these are the fluent ones");
        try w.writeAll(".\n\n");
    } else try w.print("Inherits `{s}`.", .{c.root.type_name.name});
    const doc = comment(f.src, c.span.start);
    if (doc.len > 0) try w.print("{s}{s}\n", .{ if (c.is_global) "" else " ", oneLine(doc) }) else if (!c.is_global) try w.writeAll("\n");

    var props: usize = 0;
    for (c.root.members) |m| if (m == .property and m.property.visibility != .private) {
        if (props == 0) try w.writeAll("\n| Property | Type | Access | Default | Description |\n|---|---|---|---|---|\n");
        props += 1;
        const p = m.property;
        try w.print("| `{s}` | {s} | {s} | ", .{ p.name.name, typeText(p.type_name), switch (p.visibility) {
            .in => "in",
            .out => "out",
            .in_out => "in-out",
            .private => unreachable,
        } });
        // The default of an input; outputs are computed.
        if (p.init) |e| if (p.visibility != .out or c.is_global) {
            const text = collapse(f.src[e.span.start..e.span.end]);
            if (text.len <= 48) try w.print("`{s}`", .{text});
        };
        try w.print(" | {s} |\n", .{oneLine(comment(f.src, p.span.start))});
    };
    var first = true;
    for (c.root.members) |m| switch (m) {
        .callback => |cb| {
            if (first) try w.writeAll("\nCallbacks:\n\n");
            first = false;
            try w.print("- `{s}(", .{cb.name.name});
            for (cb.params, 0..) |p, i| try w.print("{s}{s}", .{ if (i > 0) ", " else "", p.name });
            try w.writeAll(")");
            if (cb.ret) |r| try w.print(" -> {s}", .{r.name});
            try w.writeAll("`");
            try describe(w, f.src, cb.span.start);
        },
        else => {},
    };
    first = true;
    for (c.root.members) |m| switch (m) {
        .function => |fd| if (fd.public) {
            if (first) try w.writeAll("\nFunctions:\n\n");
            first = false;
            try w.print("- `{s}(", .{fd.name.name});
            for (fd.params, 0..) |p, i| try w.print("{s}{s}: {s}", .{ if (i > 0) ", " else "", p.name.name, typeText(p.type_name) });
            try w.writeAll(")");
            if (fd.ret) |r| try w.print(" -> {s}", .{typeText(r)});
            try w.writeAll("`");
            try describe(w, f.src, fd.span.start);
        },
        else => {},
    };
}

fn describe(w: *std.Io.Writer, src: []const u8, at: u32) !void {
    const doc = comment(src, at);
    if (doc.len > 0) try w.print(": {s}", .{oneLine(doc)});
    try w.writeAll("\n");
}

/// `int`, `[string]` or `[[string]]`.
fn typeText(t: ast.TypeRef) []const u8 {
    const S = struct {
        var buf: [64]u8 = undefined;
    };
    if (!t.model) return t.name.name;
    return std.fmt.bufPrint(&S.buf, "{s}{s}{s}", .{ if (t.nested) "[[" else "[", t.name.name, if (t.nested) "]]" else "]" }) catch t.name.name;
}

/// The `//` comment lines right above the line of `at`, joined.
fn comment(src: []const u8, at: u32) []const u8 {
    var line_start = std.mem.lastIndexOfScalar(u8, src[0..at], '\n') orelse return "";
    var first: ?usize = null;
    var last_end: usize = 0;
    while (line_start > 0) {
        const prev_start = if (std.mem.lastIndexOfScalar(u8, src[0..line_start], '\n')) |i| i + 1 else 0;
        const line = std.mem.trim(u8, src[prev_start..line_start], " \t");
        if (!std.mem.startsWith(u8, line, "//")) break;
        if (first == null) last_end = line_start;
        first = prev_start;
        if (prev_start == 0) break;
        line_start = prev_start - 1;
    }
    return if (first) |s| src[s..last_end] else "";
}

/// Comment lines as one line of text.
fn oneLine(block: []const u8) []const u8 {
    // Stored in a static buffer: the documentation is generated once.
    const S = struct {
        var buf: [4096]u8 = undefined;
    };
    var n: usize = 0;
    var lines = std.mem.splitScalar(u8, block, '\n');
    while (lines.next()) |raw| {
        var line = std.mem.trim(u8, raw, " \t");
        if (std.mem.startsWith(u8, line, "//")) line = std.mem.trim(u8, line[2..], " ");
        if (line.len == 0) continue;
        if (n > 0) {
            S.buf[n] = ' ';
            n += 1;
        }
        @memcpy(S.buf[n..][0..line.len], line);
        n += line.len;
    }
    return S.buf[0..n];
}

/// Source text on one line, with runs of whitespace as one space.
fn collapse(text: []const u8) []const u8 {
    const S = struct {
        var buf: [256]u8 = undefined;
    };
    var n: usize = 0;
    var space = false;
    for (text) |ch| {
        if (ch == ' ' or ch == '\n' or ch == '\t') {
            space = true;
            continue;
        }
        if (n + 2 >= S.buf.len) break;
        if (space and n > 0) {
            S.buf[n] = ' ';
            n += 1;
        }
        space = false;
        S.buf[n] = ch;
        n += 1;
    }
    return S.buf[0..n];
}
